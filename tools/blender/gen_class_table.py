#!/usr/bin/env python3
"""Render the asset-class table of CONVENTIONS.md from dinkasset/conventions.py.

    python3 gen_class_table.py            # print the table
    python3 gen_class_table.py --write    # replace the block between the BEGIN/END markers in CONVENTIONS.md

run_tests.py fails if CONVENTIONS.md and conventions.py disagree. Plain Python, no Blender needed.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from dinkasset import conventions as C  # noqa: E402

BEGIN = "<!-- BEGIN CLASS TABLE (generated by gen_class_table.py) -->"
END = "<!-- END CLASS TABLE -->"


def render():
    rows = ["| Class | Prefix | Pivot rule | Longest side (m) | Tris target / hard max (LOD0) | Mat. slots | Collision | Nanite | LOD levels required | Unique UVs | Texel density (px/m) | Max texture |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, c in C.CLASSES.items():
        rows.append("| `%s` | %s_ | `%s` | %g-%g | %s / %s | %d | %s | %s | %s | %s | %s | %d |" % (
            name, C.SKELETAL_PREFIX if c["kind"] == "skeletal" else C.STATIC_PREFIX, c["pivot"],
            c["longest"][0], c["longest"][1], format(c["tris"][0], ","), format(c["tris"][1], ","), c["slots"],
            "required" if c["collision"] else "optional" if c["kind"] == "static" else "Physics Asset",
            {"yes": "yes", "no": "no", "verify": "verify"}[c["nanite"]],
            ("%d (LOD0-LOD%d)" % (c["lods"], c["lods"] - 1)) if c["lods"] else "none",
            "no (overlap ok)" if c["uv_overlap"] else "yes",
            c["texel"] if c.get("texel_check") else "trim sheet / n.a.", c["tex_max"]))
    return BEGIN + "\n" + "\n".join(rows) + "\n" + END


def main():
    table = render()
    if "--write" not in sys.argv:
        print(table)
        return
    path = os.path.join(HERE, "CONVENTIONS.md")
    with open(path) as f:
        text = f.read()
    a, b = text.index(BEGIN), text.index(END) + len(END)
    with open(path, "w") as f:
        f.write(text[:a] + table + text[b:])
    print("updated", path)


if __name__ == "__main__":
    main()
