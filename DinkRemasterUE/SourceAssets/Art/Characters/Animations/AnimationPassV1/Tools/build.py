"""Build, measure, review and export the AnimationPassV1 clips.

  blender -b -t 4 --python Tools/build.py -- [--only name,name] [--strips] [--export] [--character hero|mother|milder]

Clips are generated by code (rig.py, gait.py, clips_*.py) on the shared 89-bone rig; nothing is
keyed by hand in a .blend, so this script is the source. --strips renders contact strips (side and
front, ground ticks that travel with the ground, red marks under planted feet) to Strips/;
--export writes armature-only centimetre FBX files to Export/ and animation_manifest.json.
"""
import bpy, sys, os, json, math, subprocess, hashlib
from pathlib import Path
from mathutils import Matrix, Vector

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
CHARS = ROOT.parents[1]
sys.path.insert(0, str(HERE))
import rig as rigmod
from rig import Rig, sole_points

CHARACTERS = {
    'hero': ('Dink/HandBindingV2/SK_Dink_Hands.blend', 'SK_Dink_Hands_LOD0'),
    'mother': ('SK_Mother.blend', None),
    'milder': ('Milder/SK_Milder.blend', None),
}


def arguments():
    argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
    out = dict(only=None, strips=False, export=False, character='hero', every=None, tag='')
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == '--only':
            out['only'] = argv[i + 1].split(','); i += 1
        elif a == '--strips':
            out['strips'] = True
        elif a == '--export':
            out['export'] = True
        elif a == '--character':
            out['character'] = argv[i + 1]; i += 1
        elif a == '--every':
            out['every'] = int(argv[i + 1]); i += 1
        elif a == '--tag':
            out['tag'] = argv[i + 1]; i += 1
        i += 1
    return out


def open_character(kind):
    blend, mesh_name = CHARACTERS[kind]
    bpy.ops.wm.open_mainfile(filepath=str(CHARS / blend))
    scene = bpy.context.scene
    arm = next(o for o in scene.objects if o.type == 'ARMATURE')
    meshes = [o for o in scene.objects if o.type == 'MESH']
    lod0 = [o for o in meshes if o.name.endswith('_LOD0')] or meshes
    keep = lod0[0] if mesh_name is None else bpy.data.objects[mesh_name]
    for o in list(scene.objects):
        if o.type == 'MESH' and o is not keep and '_LOD' in o.name:
            bpy.data.objects.remove(o, do_unlink=True)
    for o in scene.objects:
        if o.type == 'MESH':
            o.hide_render = False
    arm.data.pose_position = 'POSE'
    for b in arm.pose.bones:
        b.rotation_mode = 'QUATERNION'
        b.matrix_basis = Matrix.Identity(4)
    return scene, arm, keep


def key_clip(arm, clip, loc_scale=1.0):
    name = clip['name']
    old = bpy.data.actions.get(name)
    if old:
        bpy.data.actions.remove(old)
    act = bpy.data.actions.new(name)
    arm.animation_data_create()
    arm.animation_data.action = act
    identity = Matrix.Identity(4)
    for i, pose in enumerate(clip['poses']):
        frame = i + 1
        for pb in arm.pose.bones:
            b = pose.basis.get(pb.name, identity)
            loc, q, _ = b.decompose()
            pb.location = loc * loc_scale
            if i and pb.get('_q') is not None and Vector(pb['_q']).dot(Vector(q)) < 0:
                q.negate()
            pb['_q'] = list(q)
            pb.rotation_quaternion = q
            pb.scale = (1, 1, 1)
            pb.keyframe_insert('location', frame=frame, group=pb.name)
            pb.keyframe_insert('rotation_quaternion', frame=frame, group=pb.name)
            pb.keyframe_insert('scale', frame=frame, group=pb.name)
    for pb in arm.pose.bones:
        if '_q' in pb:
            del pb['_q']
    return act


def measure(clip):
    """Planted-foot drift in the ground frame, IK clamps, loop seam: all from the final poses."""
    fps, v = clip['fps'], clip.get('speed', 0.0)
    poses = clip['poses']
    drifts, clamps, low = [], 0, 9.0
    prev = None
    flags = clip.get('contacts')
    for i, pose in enumerate(poses):
        clamps += len(pose.clamped)
        t = i / fps
        pts = {}
        for side in 'lr':
            heel, ball = sole_points(pose, side)
            low = min(low, heel.z, ball.z)
            for tag, p in (('heel', heel), ('ball', ball)):
                # A point is planted when it rests on the ground (under 6 mm); where the generator
                # says the foot is in swing it is not counted (the toe leaving, the heel arriving).
                stance = flags[i][side] if flags else True
                pts[side + tag] = (Vector((p.x, p.y - v * t)), p.z if stance else 1.0)
        if prev:
            for k, (g, z) in pts.items():
                g0, z0 = prev[k]
                if z < 0.006 and z0 < 0.006:
                    drifts.append((g - g0).length * 100.0)
        prev = pts
    seam = 0.0
    if clip.get('loop'):
        a, b = poses[0].world(), poses[-1].world()
        seam = max((a[n].translation - b[n].translation).length for n in a)
    drifts.sort()
    return dict(frames=len(poses), fps=fps, duration_s=(len(poses) - 1) / fps, speed_m_s=v, stride_m=clip.get('stride', 0.0),
                planted_samples=len(drifts), planted_drift_cm_per_frame_max=round(drifts[-1], 4) if drifts else 0.0,
                planted_drift_cm_per_frame_mean=round(sum(drifts) / len(drifts), 4) if drifts else 0.0,
                planted_slide_cm_per_s_max=round(drifts[-1] * fps, 3) if drifts else 0.0,
                ik_clamps=clamps, lowest_sole_m=round(low, 4), loop_seam_m=round(seam, 6))


def setup_review(scene, arm, mesh):
    scene.render.engine = 'BLENDER_WORKBENCH'
    sh = scene.display.shading
    sh.light = 'STUDIO'
    sh.color_type = 'TEXTURE'
    sh.show_cavity = True
    sh.show_shadows = False
    sh.show_object_outline = True
    scene.render.film_transparent = False
    scene.world = scene.world or bpy.data.worlds.new('W')
    scene.display.render_aa = '5'
    for o in list(scene.objects):
        if o.type in ('LIGHT', 'CAMERA'):
            bpy.data.objects.remove(o, do_unlink=True)
    cam = bpy.data.objects.new('ReviewCam', bpy.data.cameras.new('ReviewCam'))
    scene.collection.objects.link(cam)
    cam.data.type = 'ORTHO'
    scene.camera = cam

    def box(name, size, loc, colour):
        m = bpy.data.meshes.new(name)
        x, y, z = (s / 2 for s in size)
        m.from_pydata([(-x, -y, -z), (x, -y, -z), (x, y, -z), (-x, y, -z), (-x, -y, z), (x, -y, z), (x, y, z), (-x, y, z)], [],
                      [(0, 1, 2, 3), (4, 7, 6, 5), (0, 4, 5, 1), (1, 5, 6, 2), (2, 6, 7, 3), (3, 7, 4, 0)])
        o = bpy.data.objects.new(name, m)
        o.location = loc
        mat = bpy.data.materials.new(name)
        mat.diffuse_color = colour
        m.materials.append(mat)
        scene.collection.objects.link(o)
        return o
    ground = box('Ground', (3.2, 3.6, 0.02), (0, 0, -0.011), (0.42, 0.42, 0.40, 1))
    ticks = bpy.data.objects.new('Ticks', None)
    scene.collection.objects.link(ticks)
    for i in range(-5, 6):
        t = box('Tick%d' % i, (3.2, 0.03, 0.022), (0, i * 0.5, -0.0105), (0.9, 0.9, 0.85, 1))
        t.parent = ticks
        post = box('Post%d' % i, (0.03, 0.03, 0.10), (-0.42, i * 0.5, 0.05), (0.95, 0.85, 0.2, 1))
        post.parent = ticks
    marks = {k: box('Mark_' + k, (0.07, 0.07, 0.012), (0, 0, -1), (0.95, 0.1, 0.1, 1)) for k in ('lheel', 'lball', 'rheel', 'rball')}
    return cam, ticks, marks


def render_strip(scene, arm, clip, cam, ticks, marks, out, every, label):
    fps, v = clip['fps'], clip.get('speed', 0.0)
    n = len(clip['poses'])
    frames = list(range(0, n, every))
    tmp = Path(bpy.app.tempdir) / ('strip_' + clip['name'])
    tmp.mkdir(parents=True, exist_ok=True)
    views = {'side': (Vector((6, -0.15, 0.93)), (math.radians(90), 0, math.radians(90)), 2.25, (225, 275)),
             'front': (Vector((0, -6, 0.93)), (math.radians(90), 0, 0), 2.25, (190, 275))}
    files = {k: [] for k in views}
    for i in frames:
        scene.frame_set(i + 1)
        pose = clip['poses'][i]
        t = i / fps
        ticks.location.y = (v * t) % 0.5
        for side in 'lr':
            for tag, p in zip(('heel', 'ball'), sole_points(pose, side)):
                marks[side + tag].location = (p.x, p.y, 0.004) if p.z < 0.012 else (0, 0, -1)
        for key, (loc, euler, scale, res) in views.items():
            cam.location = loc
            cam.rotation_euler = euler
            cam.data.ortho_scale = scale
            scene.render.resolution_x, scene.render.resolution_y = res
            # Ortho scale spans the larger image dimension.
            path = tmp / ('%s_%03d.png' % (key, i))
            scene.render.filepath = str(path)
            bpy.ops.render.render(write_still=True)
            files[key].append((str(path), 'f%d %.2fs' % (i, t)))
    spec = dict(out=str(out), title=label, rows=[files['side'], files['front']])
    spec_path = tmp / 'spec.json'
    spec_path.write_text(json.dumps(spec))
    subprocess.run(['python3', '-I', str(HERE / 'compose_strip.py'), str(spec_path)], check=True)


def export_fbx(scene, arm, clip, path):
    """Called in the centimetre export scene (bones already scaled by 100)."""
    act = key_clip(arm, clip, loc_scale=100.0)
    scene.render.fps = clip['fps']
    scene.frame_start, scene.frame_end = 1, len(clip['poses'])
    scene.frame_set(1)
    bpy.ops.object.select_all(action='DESELECT')
    arm.select_set(True)
    bpy.context.view_layer.objects.active = arm
    bpy.ops.export_scene.fbx(filepath=str(path), use_selection=True, object_types={'ARMATURE'}, apply_unit_scale=True,
                             global_scale=1, apply_scale_options='FBX_SCALE_ALL', axis_forward='Y', axis_up='Z',
                             bake_space_transform=False, use_space_transform=True, add_leaf_bones=False,
                             primary_bone_axis='Y', secondary_bone_axis='X', use_armature_deform_only=False,
                             armature_nodetype='NULL', bake_anim=True, bake_anim_use_all_bones=True,
                             bake_anim_use_nla_strips=False, bake_anim_use_all_actions=False,
                             bake_anim_force_startend_keying=True, bake_anim_step=1, bake_anim_simplify_factor=0,
                             path_mode='STRIP', embed_textures=False, use_custom_props=False)
    bpy.data.actions.remove(act)


def main():
    args = arguments()
    scene, arm, mesh = open_character(args['character'])
    rig = Rig.from_armature(arm)
    assert len(rig.order) == 89, len(rig.order)
    import clips
    library = clips.build(rig, args['only'])
    report = {}
    for name, clip in library.items():
        report[name] = dict(measure(clip), **{k: clip[k] for k in ('loop', 'events', 'family', 'note', 'pelvis_range_m') if k in clip})
        print('CLIP %-22s %s' % (name, json.dumps(report[name])), flush=True)
    if args['strips']:
        cam, ticks, marks = setup_review(scene, arm, mesh)
        out_dir = ROOT / 'Strips' / (args['character'] + (('_' + args['tag']) if args['tag'] else ''))
        out_dir.mkdir(parents=True, exist_ok=True)
        for name, clip in library.items():
            key_clip(arm, clip)
            every = args['every'] or clip.get('strip_every', 2)
            m = report[name]
            label = '%s  %s  %.2fs @%dfps  speed %.2f m/s  slide max %.2f cm/s  clamps %d' % (
                name, args['character'], m['duration_s'], m['fps'], m['speed_m_s'], m['planted_slide_cm_per_s_max'], m['ik_clamps'])
            render_strip(scene, arm, clip, cam, ticks, marks, out_dir / (name + '.png'), every, label)
            print('STRIP', name, flush=True)
    if args['export']:
        assert args['character'] == 'hero'
        arm.animation_data_create()
        arm.animation_data.action = None
        arm.data.pose_position = 'REST'
        bpy.ops.object.select_all(action='DESELECT')
        arm.select_set(True)
        bpy.context.view_layer.objects.active = arm
        bpy.ops.object.mode_set(mode='EDIT')
        for bone in arm.data.edit_bones:
            bone.head *= 100
            bone.tail *= 100
        bpy.ops.object.mode_set(mode='OBJECT')
        scene.unit_settings.scale_length = .01
        arm.data.pose_position = 'POSE'
        (ROOT / 'Export').mkdir(exist_ok=True)
        manifest_path = ROOT / 'animation_manifest.json'
        manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {
            'schema': 'dink-animation-pass/1', 'skeleton_from_mesh': '/Game/Dink/Hero/SK_Dink.SK_Dink',
            'content_folder': '/Game/Dink/Hero/Animations/Pass1', 'clips': {}}
        for name, clip in library.items():
            fbx = ROOT / 'Export' / ('A_' + name + '.fbx')
            export_fbx(scene, arm, clip, fbx)
            manifest['clips'][name] = dict(report[name], fbx='Export/' + fbx.name, asset_name='AN_' + name,
                                           sha256=hashlib.sha256(fbx.read_bytes()).hexdigest())
            print('EXPORT', name, flush=True)
        manifest['clips'] = dict(sorted(manifest['clips'].items()))
        manifest_path.write_text(json.dumps(manifest, indent=1) + '\n')
    (Path(bpy.app.tempdir) / 'animation_pass_report.json').write_text(json.dumps(report, indent=1))
    print('ANIMATION PASS BUILD OK: %d clips' % len(library), flush=True)


main()
