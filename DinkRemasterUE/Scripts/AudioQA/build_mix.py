#!/usr/bin/env python3
"""Per-take loudness gains for the approved effects and music: Content/Dink/Data/Audio/mix.json (read by UDinkAudioSubsystem).

The reviewed takes were peak-normalised (-3 dBFS) when they were prepared, so a dense one (hurt1, attack1, the scream) plays about
20 dB louder than a sparse one (fire, picker). A gain per take brings each effect into a window around the category's target and
each music cue to one level, never past a true-peak ceiling. The takes themselves are untouched (no re-import, no new review).

  python3 -I Scripts/AudioQA/build_mix.py [--assets <checkout with LFS-pulled SourceAssets/Audio>] [--check]

Targets are integrated loudness in the game, after the category volume of approved.json (sfx 0.8, music 0.35):
  effects: squeezed into [-26, -17] LUFS (a quiet one is lifted at most to its peak ceiling, a loud one brought down);
  music:   -27 LUFS, so speech (median about -18.6 LUFS) stays 8 dB above it;
  voice:   only lines outside [-24, -13] LUFS move to its edge (whispers and screams keep their character).
"""
import argparse, json, math, re, subprocess, sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[2]
SFX_WINDOW = (-26.0, -17.0)
MUSIC_TARGET = -27.0
VOICE_WINDOW = (-24.0, -13.0)  # acted speech keeps its whispers and shouts, only the extremes move (about one line in ten)
PEAK_CEILING = -1.0  # dBFS after gain and category volume (music, voice: 2D or speech-width)
# Effects are mono and positional: panned fully to one speaker the equal-power law gives +3 dB over a centred 2D play, so their ceiling
# is 3 dB lower (recorded 15 Nov 2026: the fireplace loop, lifted +3.5 dB to a 2D -1 dBFS, reached 0 dBFS on the right channel).
SFX_PEAK_CEILING = PEAK_CEILING - 3.0


def measure(path: Path):
    r = subprocess.run(['ffmpeg', '-hide_banner', '-nostats', '-i', str(path), '-af', 'ebur128=peak=true', '-f', 'null', '-'], capture_output=True, text=True)
    i = re.findall(r'I:\s+(-?[0-9.]+) LUFS', r.stderr)
    p = re.findall(r'Peak:\s+(-?[0-9.]+) dBFS', r.stderr)
    if not i or not p:
        raise SystemExit(f'MIX FAILED: cannot measure {path}')
    return float(i[-1]), float(p[-1])


def gain_for(lufs, peak, volume, lo, hi, ceiling=PEAK_CEILING):
    db_vol = 20 * math.log10(volume)
    level = lufs + db_vol
    want = min(max(level, lo), hi)
    g_db = want - level
    g_db = min(g_db, ceiling - (peak + db_vol))  # never push the peak past the ceiling
    return round(10 ** (g_db / 20), 3), round(level, 1), round(level + g_db, 1)


def build(assets: Path, cache_path: Path) -> dict:
    data = PROJECT / 'Content/Dink/Data/Audio'
    approved = json.loads((data / 'approved.json').read_text())
    manifest = json.loads((assets / 'SourceAssets/Audio/selection_manifest.json').read_text())
    src = {f"{a['folder']}/{a['name']}.{a['name']}": assets / a['source'] for a in manifest['assets']}
    vol = approved['volumes']
    sfx, music, report = {}, {}, []
    for k, e in sorted(approved['sounds'].items(), key=lambda kv: int(kv[0])):
        lufs, peak = measure(src[e['asset']])
        g, before, after = gain_for(lufs, peak, vol['sfx'], *SFX_WINDOW, ceiling=SFX_PEAK_CEILING)
        sfx[k] = g
        report.append(('sfx', k, before, after, g))
    for asset in sorted({e['asset'] for e in approved['music'].values()}):
        lufs, peak = measure(src[asset])
        g, before, after = gain_for(lufs, peak, vol['music'], MUSIC_TARGET, MUSIC_TARGET)
        music[asset] = g
        report.append(('music', asset.split('.')[-1], before, after, g))
    voice = json.loads((data / 'voice.json').read_text())
    cache = json.loads(cache_path.read_text()) if cache_path.is_file() else {}
    vgain = {}
    for line, e in sorted(voice['lines'].items()):
        src = assets / 'SourceAssets/Audio/Voice' / e.get('voice', '') / f'{line}.mp3'
        if str(src) not in cache:
            cache[str(src)] = list(measure(src))
        lufs, peak = cache[str(src)]
        g, before, after = gain_for(lufs, peak, voice.get('volume', 1.0), *VOICE_WINDOW)
        if g != 1.0:
            vgain[line] = g
            report.append(('voice', line, before, after, g))
    cache_path.parent.mkdir(parents=True, exist_ok=True)
    cache_path.write_text(json.dumps(cache))
    return {
        'schema': 'dink-audio-mix/1',
        'note': 'Generated by Scripts/AudioQA/build_mix.py from the source takes (ffmpeg ebur128); never hand-edit. Gains multiply the category volume.',
        'targets': {'sfx_window_lufs': list(SFX_WINDOW), 'music_lufs': MUSIC_TARGET, 'voice_window_lufs': list(VOICE_WINDOW), 'peak_ceiling_dbfs': PEAK_CEILING, 'sfx_peak_ceiling_dbfs': SFX_PEAK_CEILING},
        'sfx': sfx,
        'music': music,
        'voice': vgain,
        'report': [{'kind': r[0], 'key': r[1], 'lufs_before': r[2], 'lufs_after': r[3], 'gain': r[4]} for r in report],
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--assets', default=str(PROJECT))
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--cache', default=str(PROJECT / 'Saved/AudioQA/loudness_sources.json'))
    a = ap.parse_args(argv)
    mix = build(Path(a.assets), Path(a.cache))
    text = json.dumps(mix, indent=1, sort_keys=True) + '\n'
    out = PROJECT / 'Content/Dink/Data/Audio/mix.json'
    if a.check:
        ok = out.is_file() and out.read_text() == text
        print('MIX ' + ('OK' if ok else 'DIFFERS'))
        return 0 if ok else 1
    out.write_text(text)
    b = [r['lufs_before'] for r in mix['report'] if r['kind'] == 'sfx']
    c = [r['lufs_after'] for r in mix['report'] if r['kind'] == 'sfx']
    m = [r['lufs_after'] for r in mix['report'] if r['kind'] == 'music']
    v = [r for r in mix['report'] if r['kind'] == 'voice']
    print(f'MIX OK: sfx {min(b)}..{max(b)} -> {min(c)}..{max(c)} LUFS; music -> {min(m)}..{max(m)} LUFS; voice lines levelled: {len(v)} of 2088')
    return 0


if __name__ == '__main__':
    sys.exit(main())
