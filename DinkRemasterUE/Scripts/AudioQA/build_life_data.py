#!/usr/bin/env python3
"""Build Content/Dink/Data/Audio/life.json: what the ground under each foot sounds like, which ambience bed each screen
plays, and which sound each map.dat warp makes (read by UDinkAudioLifeSubsystem, DinkAudioLife.cpp).

Inputs (all in the repository): the extracted screens (tools/dinkex/out/screens/SCR_*.json, `python3 -m dinkex extract`),
the tile classes (tools/data/tile_classes.csv, the same table the importer colours the ground with) and the placements
(DinkRemasterUE/Content/Dink/Data/Gameplay/placements.csv).

  python3 -I Scripts/AudioQA/build_life_data.py [--data <repo root>] [--check]

Surfaces, one letter per 50 px tile in screen order (12 x 8, row by row):
  g grass   d dirt/path/gravel   s sand   w wood   t stone   n snow/ice   a water   - none (void, walls, chasm)
Ambience beds: sea, cave, wind (snow, ice, wasteland, lava), meadow (grass and forest), none (indoor).
"""
import argparse, csv, json, sys
from collections import Counter
from pathlib import Path

SURFACE = {
    'grass': 'g', 'forest_canopy': 'g', 'grass_rocky': 'd', 'path': 'd', 'gravel': 'd', 'dirt': 'd', 'wasteland': 'd',
    'sand': 's', 'wood_floor': 'w', 'stone_floor': 't', 'cave_floor': 't', 'cliff_face': 't', 'rock_mass': 't',
    'cave_wall': 't', 'structure_facade': 't', 'lava': 't', 'snow': 'n', 'ice': 'n', 'water': 'a',
    'void': '-', 'chasm': '-',
}
# Warp sound when a map.dat warp's own sound is 0: SoundPlayEffect(7, 12000, ...) (dink.cpp:15343-15345).
WARP_DEFAULT = {'sound': 7, 'speed': 12000}


def ambience(classes: Counter, indoor: bool) -> str:
    n = sum(classes.values()) or 1
    f = lambda *names: sum(classes.get(c, 0) for c in names) / n
    if indoor:
        return 'cave' if f('cave_floor', 'cave_wall') >= 0.2 else 'none'
    if f('cave_floor', 'cave_wall') >= 0.2:
        return 'cave'
    if f('water') >= 0.12 and f('sand') >= 0.06:
        return 'sea'
    if f('snow', 'ice') >= 0.2 or f('wasteland', 'lava') >= 0.3:
        return 'wind'
    if f('water') >= 0.45:
        return 'sea'
    return 'meadow'


def build(root: Path) -> dict:
    ue = root / 'DinkRemasterUE'
    tiles = {int(r['tile_num']): r['terrain'] for r in csv.DictReader(open(root / 'tools/data/tile_classes.csv', encoding='utf-8'))}
    screens, beds, unknown = {}, Counter(), Counter()
    for f in sorted((root / 'tools/dinkex/out/screens').glob('SCR_*.json')):
        s = json.loads(f.read_text())
        grid = ['-'] * 96
        classes = Counter()
        for t in s['tiles']:
            cls = tiles.get(int(t['num']), '')
            classes[cls] += 1
            letter = SURFACE.get(cls)
            if letter is None:
                unknown[cls] += 1
                letter = 'g'
            grid[int(t['row']) * 12 + int(t['col'])] = letter
        bed = ambience(classes, bool(s.get('indoor')))
        beds[bed] += 1
        screens[str(s['screen'])] = {'surface': ''.join(grid), 'ambience': bed}
    warps = {}
    for p in csv.DictReader(open(ue / 'Content/Dink/Data/Gameplay/placements.csv', encoding='utf-8')):
        if p['warp_map'] not in ('', '0'):
            sound = int(p['sound'] or 0)
            warps[p['origin']] = {'sound': sound, 'speed': 22050} if sound else dict(WARP_DEFAULT)
    return {
        'schema': 'dink-audio-life/1',
        'note': 'Generated by Scripts/AudioQA/build_life_data.py; never hand-edit. Surfaces: g grass, d dirt, s sand, w wood, t stone, n snow, a water, - none; 12 x 8 tiles of 50 px, row by row.',
        'screens': screens,
        'warps': warps,
        'stats': {'screens': len(screens), 'beds': dict(sorted(beds.items())), 'warps': len(warps), 'unknown_classes': dict(unknown)},
    }


def main(argv=None) -> int:
    here = Path(__file__).resolve().parents[3]
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--data', default=str(here), help='repository root holding tools/ and DinkRemasterUE/')
    ap.add_argument('--out', default=str(here / 'DinkRemasterUE/Content/Dink/Data/Audio/life_data.json'))
    ap.add_argument('--check', action='store_true', help='fail if the file on disk differs')
    a = ap.parse_args(argv)
    data = build(Path(a.data))
    text = json.dumps(data, indent=1, sort_keys=True) + '\n'
    out = Path(a.out)
    if a.check:
        ok = out.is_file() and out.read_text() == text
        print('LIFE DATA ' + ('OK' if ok else 'DIFFERS') + f': {out}')
        return 0 if ok else 1
    out.write_text(text)
    print('LIFE DATA OK:', json.dumps(data['stats']))
    return 0


if __name__ == '__main__':
    sys.exit(main())
