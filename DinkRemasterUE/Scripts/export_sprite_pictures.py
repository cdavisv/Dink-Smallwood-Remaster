#!/usr/bin/env python3
"""Pictures a script-created sprite may show, for the picture card of UDinkArtFamilySubsystem::DressScriptSprite.

    python3 -I Scripts/export_sprite_pictures.py [--dinkex ../tools/dinkex/out] [--check]

Writes Content/Dink/Data/Art/sprite_pictures.json: for every frame of the 1997 sequences a script can give a sprite
(people, foes, animals, effects, items, bonuses, structures, lands, interiors; not the map tiles, not Dink's own
sequences, not the interface) its pixel size and origin, "<seq>_<frame:02d>": [width, height, origin_x, origin_y].
The import bundle (Scripts/export_import_bundle.py) imports a texture and MI_Sprite material for every key listed
here, so a sprite whose picture has no family mesh is drawn as its 1997 picture on a card instead of the grey marker.
Sequences a script replaces with init("load_sequence_now <file> <seq> ...") (Seth's pose 580 and walks 581/583/587/589 in
s7-mil.c, over dink.ini's green gnome; figure_out, dink.cpp:2335-2366) are listed as "init_<file>_<frame:02d>" with the
line's origin; the bundle imports their frames from the 1997 archives (init_frames) and the runtime shows them once the
line has run (UDinkArtFamilySubsystem::RegisterInitSequencePicture). Hero sequences (graphics\\dink\\...) are skipped.
--check exits 1 when the file is not what the extractor's sequences.json and the story's init lines give."""
import json, pathlib, re, sys

HERE = pathlib.Path(__file__).resolve().parent.parent
SKIP = ("tiles/", "graphics/dink/", "graphics/inter/", "graphics/startme/")


def pictures(sequences: list) -> dict:
    out = {}
    for q in sorted(sequences, key=lambda q: q["seq"]):
        if q["path"].startswith(SKIP):
            continue
        for f in q["frames"]:
            if f.get("empty") or not f.get("width") or not f.get("height") or not f.get("image"):
                continue
            o = f.get("origin") or q.get("ini_origin") or {"x": f["width"] // 2, "y": f["height"]}
            out[f"{q['seq']}_{f['frame']:02d}"] = [f["width"], f["height"], o["x"], o["y"]]
    return out


INIT_RE = re.compile(r'init\(\s*"(load_sequence(?:_now)?\s+[^"]+)"', re.IGNORECASE)


def init_lines(story_texts: dict) -> list:
    """Distinct init load_sequence lines of the story (not the hero's): [(seq, path, xoff, yoff, keyword)] sorted by seq."""
    out = {}
    for text in story_texts.values():
        for m in INIT_RE.finditer(text):
            w = m.group(1).split()
            if len(w) < 3 or not w[2].isdigit():
                continue
            path = w[1].replace("\\", "/")
            if path.lower().startswith("graphics/dink/"):
                continue
            kw = w[3].upper() if len(w) > 3 and not w[3].lstrip("-").isdigit() else ""
            num = lambda i: int(w[i]) if len(w) > i and w[i].lstrip("-").isdigit() else 0
            out[(int(w[2]), path)] = (int(w[2]), path, num(4) if not kw else 0, num(5) if not kw else 0, kw)
    return sorted(out.values())


def init_stem(path: str) -> str:
    return "init_" + "".join(c for c in path.rsplit("/", 1)[-1].lower() if c.isalnum())


def init_frames(data_dir: pathlib.Path, story_texts: dict) -> dict:
    """{"init_<file>_<NN>": (RGBA image, [w, h, origin x, origin y])} for every init sequence's frames in the 1997 archives."""
    sys.path.insert(0, str(pathlib.Path(data_dir).resolve().parent.parent / "tools/dinkex"))   # <repo>/bin/dink -> <repo>/tools/dinkex
    from dinkex.gfx import Graphics
    from dinkex.bmp import to_rgba
    from dinkex.sequences import default_origin
    gfx = Graphics(str(data_dir))
    out = {}
    for seq, path, xoff, yoff, kw in init_lines(story_texts):
        frames, _ = gfx.frames(path)
        key_colour = "black" if kw == "BLACK" else "white"
        origin = None
        for n, src in enumerate(frames, 1):
            img = to_rgba(src.read(), key_colour)
            w, h = img.size
            if origin is None:   # an animation's frame 1 fixes the origin of every frame (D:1798-1830)
                dx, dy = default_origin(w, h)
                origin = (xoff if xoff > 0 else dx, yoff if yoff > 0 else dy)
            out[f"{init_stem(path)}_{n:02d}"] = (img, [w, h, origin[0], origin[1]])
    return out


def main():
    args = sys.argv[1:]
    dinkex = pathlib.Path(args[args.index("--dinkex") + 1]) if "--dinkex" in args else HERE.parent / "tools/dinkex/out"
    seqs = json.loads((dinkex / "sequences.json").read_text())["sequences"]
    data = {"schema": "dink-sprite-pictures/1",
            "about": "Generated by Scripts/export_sprite_pictures.py from the extracted 1997 sequences: "
                     "<seq>_<frame> -> [width px, height px, origin x, origin y]. Do not edit by hand.",
            "pictures": pictures(seqs)}
    story = {p.stem: p.read_text(errors="replace") for p in sorted((HERE.parent / "bin/dink/story").glob("*.c"))}
    data["pictures"].update({k: v[1] for k, v in sorted(init_frames(HERE.parent / "bin/dink", story).items())})
    text = json.dumps(data, indent=0, sort_keys=False).replace("\n", "") + "\n"
    target = HERE / "Content/Dink/Data/Art/sprite_pictures.json"
    if "--check" in args:
        same = target.exists() and json.loads(target.read_text()) == data
        print("sprite_pictures.json %s (%d pictures)" % ("up to date" if same else "STALE", len(data["pictures"])))
        sys.exit(0 if same else 1)
    target.write_text(text)
    print("%d pictures -> %s" % (len(data["pictures"]), target))


if __name__ == "__main__":
    main()
