#!/usr/bin/env python3
"""Pictures a script-created sprite may show, for the picture card of UDinkArtFamilySubsystem::DressScriptSprite.

    python3 -I Scripts/export_sprite_pictures.py [--dinkex ../tools/dinkex/out] [--check]

Writes Content/Dink/Data/Art/sprite_pictures.json: for every frame of the 1997 sequences a script can give a sprite
(people, foes, animals, effects, items, bonuses, structures, lands, interiors; not the map tiles, not Dink's own
sequences, not the interface) its pixel size and origin, "<seq>_<frame:02d>": [width, height, origin_x, origin_y].
The import bundle (Scripts/export_import_bundle.py) imports a texture and MI_Sprite material for every key listed
here, so a sprite whose picture has no family mesh is drawn as its 1997 picture on a card instead of the grey marker.
--check exits 1 when the file is not what the extractor's sequences.json gives."""
import json, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent.parent
SKIP = ("tiles/", "graphics/dink/", "graphics/inter/", "graphics/startme/")


def pictures(sequences: list) -> dict:
    out = {}
    for q in sorted(sequences, key=lambda q: q["seq"]):
        if q["path"].startswith(SKIP):
            continue
        for f in q["frames"]:
            if f.get("empty") or not f.get("width") or not f.get("height") or not f.get("image"):
                continue
            o = f.get("origin") or q.get("ini_origin") or {"x": f["width"] // 2, "y": f["height"]}
            out[f"{q['seq']}_{f['frame']:02d}"] = [f["width"], f["height"], o["x"], o["y"]]
    return out


def main():
    args = sys.argv[1:]
    dinkex = pathlib.Path(args[args.index("--dinkex") + 1]) if "--dinkex" in args else HERE.parent / "tools/dinkex/out"
    seqs = json.loads((dinkex / "sequences.json").read_text())["sequences"]
    data = {"schema": "dink-sprite-pictures/1",
            "about": "Generated by Scripts/export_sprite_pictures.py from the extracted 1997 sequences: "
                     "<seq>_<frame> -> [width px, height px, origin x, origin y]. Do not edit by hand.",
            "pictures": pictures(seqs)}
    text = json.dumps(data, indent=0, sort_keys=False).replace("\n", "") + "\n"
    target = HERE / "Content/Dink/Data/Art/sprite_pictures.json"
    if "--check" in args:
        same = target.exists() and json.loads(target.read_text()) == data
        print("sprite_pictures.json %s (%d pictures)" % ("up to date" if same else "STALE", len(data["pictures"])))
        sys.exit(0 if same else 1)
    target.write_text(text)
    print("%d pictures -> %s" % (len(data["pictures"]), target))


if __name__ == "__main__":
    main()
